# Dimensões da caixa retangular
comprimento = 12  # cm
largura = 14      # cm
altura = 20       # cm

# Cálculo do volume
volume = comprimento * largura * altura

# Exibição do resultado em cm³
# O resultado abaixo mostra o volume calculado da caixa retangular em centímetros cúbicos.
print(f"volume = {comprimento} * {largura} * {altura} = {volume} ")
print(f"O volume da caixa retangular é: {volume} cm³")